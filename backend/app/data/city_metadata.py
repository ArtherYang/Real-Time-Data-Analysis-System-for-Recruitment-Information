def get_city_list() -> List[dict]:
    """获取城市列表（含坐标和图标），供前端地图组件使用。

    Returns:
        [{name, lng, lat, icon, province, region}, ...]
    """
    return [
        {
            "name": name,
            "lng": meta["lng"],
            "lat": meta["lat"],
            "icon": meta["icon"],
            "province": meta["province"],
            "region": CITY_REGIONS.get(name, ""),
        }
        for name, meta in CITY_METADATA.items()
    ]


def get_city_coords(city: str) -> Tuple[float, float]:
    """获取城市经纬度。

    Args:
        city: 城市名称

    Returns:
        (lng, lat) 元组，未知城市返回 (0, 0)
    """
    meta = CITY_METADATA.get(city)
    if meta:
        return (meta["lng"], meta["lat"])
    return (0.0, 0.0)


def get_districts(city: str) -> List[str]:
    """获取城市主要行政区列表。

    Args:
        city: 城市名称

    Returns:
        区名列表，未知城市返回空列表
    """
    return CITY_DISTRICTS.get(city, [])
